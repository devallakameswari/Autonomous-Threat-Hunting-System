"""
PDF_Generation/pdf_report.py
Generates a professional PDF threat report using ReportLab, summarizing
detected threat events, severity breakdown, and MITRE ATT&CK mappings.
"""

import os
from datetime import datetime

from reportlab.lib.pagesizes import letter
from reportlab.lib.units import inch
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
)

SEVERITY_COLORS = {
    "CRITICAL": colors.HexColor("#7f1d1d"),
    "HIGH": colors.HexColor("#b91c1c"),
    "MEDIUM": colors.HexColor("#d97706"),
    "LOW": colors.HexColor("#2563eb"),
}


def _styles():
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(
        name="ReportTitle", fontSize=22, leading=26, spaceAfter=6,
        textColor=colors.HexColor("#0f172a"),
    ))
    styles.add(ParagraphStyle(
        name="SectionHeading", fontSize=14, leading=18, spaceBefore=14, spaceAfter=8,
        textColor=colors.HexColor("#0f172a"),
    ))
    styles.add(ParagraphStyle(
        name="Body", fontSize=9.5, leading=13, textColor=colors.HexColor("#1e293b"),
    ))
    return styles


def generate_threat_report(threats: list, output_path: str, generated_by: str = "System") -> str:
    """
    threats: list of dicts, each shaped like ThreatEvent.to_dict()
    Returns the output_path once the PDF has been written.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    styles = _styles()

    doc = SimpleDocTemplate(
        output_path, pagesize=letter,
        topMargin=0.6 * inch, bottomMargin=0.6 * inch,
        leftMargin=0.6 * inch, rightMargin=0.6 * inch,
    )
    story = []

    # --- Cover / header ---
    story.append(Paragraph("Autonomous Threat Hunting System", styles["ReportTitle"]))
    story.append(Paragraph("Threat Intelligence &amp; Incident Report", styles["SectionHeading"]))
    story.append(Paragraph(
        f"Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')} &nbsp;|&nbsp; "
        f"Generated by: {generated_by} &nbsp;|&nbsp; Total findings: {len(threats)}",
        styles["Body"],
    ))
    story.append(Spacer(1, 16))

    # --- Severity summary ---
    severity_counts = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    for t in threats:
        severity_counts[t.get("severity", "LOW")] = severity_counts.get(t.get("severity", "LOW"), 0) + 1

    story.append(Paragraph("Severity Summary", styles["SectionHeading"]))
    summary_data = [["Severity", "Count"]] + [[k, str(v)] for k, v in severity_counts.items()]
    summary_table = Table(summary_data, colWidths=[2.5 * inch, 2.5 * inch])
    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f1f5f9")]),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(summary_table)
    story.append(Spacer(1, 20))

    # --- Detailed findings ---
    story.append(Paragraph("Detailed Findings", styles["SectionHeading"]))

    for t in threats:
        sev = t.get("severity", "LOW")
        color = SEVERITY_COLORS.get(sev, colors.grey)

        header_table = Table(
            [[Paragraph(f"<b>{t.get('title', 'Untitled finding')}</b>", styles["Body"]),
              Paragraph(f"<b>{sev}</b>", styles["Body"])]],
            colWidths=[4.6 * inch, 1.4 * inch],
        )
        header_table.setStyle(TableStyle([
            ("BACKGROUND", (1, 0), (1, 0), color),
            ("TEXTCOLOR", (1, 0), (1, 0), colors.white),
            ("ALIGN", (1, 0), (1, 0), "CENTER"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ]))
        story.append(header_table)

        meta_line = (
            f"Type: {t.get('threat_type', 'N/A')} &nbsp;|&nbsp; "
            f"Source IP: {t.get('source_ip', 'N/A')} &nbsp;|&nbsp; "
            f"Confidence: {t.get('confidence', 0)} &nbsp;|&nbsp; "
            f"Detected by: {t.get('detection_source', 'N/A')} &nbsp;|&nbsp; "
            f"MITRE: {t.get('mitre_techniques', 'N/A')}"
        )
        story.append(Paragraph(meta_line, styles["Body"]))
        story.append(Spacer(1, 4))

        if t.get("description"):
            story.append(Paragraph(f"<b>Description:</b> {t['description']}", styles["Body"]))
        if t.get("llm_summary"):
            story.append(Paragraph(f"<b>AI Analyst Summary:</b> {t['llm_summary']}", styles["Body"]))

        story.append(Spacer(1, 14))

    if not threats:
        story.append(Paragraph("No threats were detected in this reporting period.", styles["Body"]))

    doc.build(story)
    return output_path
